//! Coefficient symbol → `(run, |level|)` companion maps — the
//! run-level "ramp" tables of the three coefficient decode classes.
//!
//! ## Source
//!
//! Transcribed verbatim from the staged extraction
//! `docs/audio/wma/tables/wma-runlevel-mode{1,2,3}.csv` (see the
//! per-table `.meta` files and
//! `docs/audio/wma/provenance/02-extractor-univdreams-tables.md` §4a).
//! The vendor module stores one RUN and one LEVEL `u16` table per
//! coefficient descriptor; the decode routine expands a coefficient
//! VLC symbol `s` as `run = RUN[s - 2]`, `|level| = LEVEL[s - 2]`
//! (**2-based** indexing — symbols 0/1 are the reserved EOB/escape
//! sentinels, see [`crate::wire_tables::COEF_EOB_SYMBOL`] /
//! [`crate::wire_tables::COEF_ESCAPE_SYMBOL`]), and the sign is a
//! separate trailing bit that negates the level.
//!
//! Layout property (from the staged data itself): entries are grouped
//! by level — RUN counts up `0, 1, 2, …` within each constant-LEVEL
//! group and LEVEL increments between groups.
//!
//! ## Table extents vs. VLC alphabets
//!
//! Mode 2's companion table carries **1333** pairs — more than its
//! 1024-symbol VLC alphabet can address. The staged provenance (§4e)
//! notes the escape path reaches run/level indices above the VLC
//! range; the extra tail is staged here verbatim so nothing is
//! dropped, and the exact escape → index composition (if any) stays a
//! documented `[GAP]` (this crate's escape carrier reads literal run
//! and level values per the frame-layout trace).

